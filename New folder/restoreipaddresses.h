void findAddr(std::string s, std::vector<std::string> & addr, std::string toBuild, int  numdot)
{
    if (numdot == 4 && s.size() == 0)
    {
        addr.push_back(toBuild);
        return;
    }
    if (s.size() == 0)
    {
        return;
    }
    if (numdot == 4 && s.size() > 0)
    {
        return;
    }

    for (size_t i = 1; i <= 3; i ++)
    {
        std::string sliced(s.begin(), s.begin() + i);
        if (valid(sliced))
        {
            findAddr(std::string(s.begin() + i, s.end()), addr, toBuild + sliced + (numdot != 3 ? "." : "" ), numdot + 1 );
        }

    }
}
